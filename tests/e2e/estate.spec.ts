test('sales status and note persist; CSV is a real filtered download; reset requires confirmation',async({page})=>{
 await page.goto('/demos/real-estate')
 const app=page.locator('main.forma-app')
 await app.getByRole('button',{name:'Sprzedaż'}).click()
 await app.getByRole('searchbox',{name:'Szukaj numeru mieszkania'}).fill('A-03')
 await expect(app.locator('.f-roster tbody tr')).toHaveCount(1)
 await app.getByRole('combobox',{name:'A-03: status'}).selectOption('sold')
 await expect(app.getByRole('combobox',{name:'A-03: status'})).toHaveValue('sold')
 await app.locator('.f-roster tbody tr').getByRole('button',{name:'Otwórz'}).click()
 const detail=app.getByRole('dialog',{name:'Apartament A-03'})
 await detail.getByRole('textbox',{name:'Notatka zespołu sprzedaży'}).fill('Kontakt po prezentacji lokalu.')
 await detail.getByRole('button',{name:'Zapisz notatkę'}).click()
 const downloadPromise=page.waitForEvent('download')
 await app.getByRole('button',{name:/Eksport CSV/}).click()
 const download=await downloadPromise
 expect(download.suggestedFilename()).toBe('forma-apartments.csv')
 const csv=await readFile(await download.path(),'utf8')
 expect(csv).toContain('"A-03"')
 expect(csv).toContain('"sold"')
 expect(csv).toContain('"Kontakt po prezentacji lokalu."')
 expect(csv).not.toContain('"A-04"')
 await page.reload()
 await app.getByRole('button',{name:'Sprzedaż'}).click()
 await app.getByRole('searchbox',{name:'Szukaj numeru mieszkania'}).fill('A-03')
 await expect(app.getByRole('combobox',{name:'A-03: status'})).toHaveValue('sold')
 await app.locator('.f-roster tbody tr').getByRole('button',{name:'Otwórz'}).click()
 await expect(app.getByRole('textbox',{name:'Notatka zespołu sprzedaży'})).toHaveValue('Kontakt po prezentacji lokalu.')
 await app.getByRole('dialog',{name:'Apartament A-03'}).getByRole('button',{name:'Zamknij'}).click()
 await app.getByRole('button',{name:'Przywróć próbkę'}).click()
 const reset=app.getByRole('dialog',{name:'Przywrócić dane?'})
 await expect(reset).toContainText('Wszystkie zmiany statusów, notatki')
 await reset.getByRole('button',{name:'Anuluj'}).click()
 await expect(app.getByRole('combobox',{name:'A-03: status'})).toHaveValue('sold')
 await app.getByRole('button',{name:'Przywróć próbkę'}).click()
 await app.getByRole('dialog',{name:'Przywrócić dane?'}).getByRole('button',{name:'Przywróć próbkę'}).click()
 await expect(app.getByRole('combobox',{name:'A-03: status'})).toHaveValue('available')
 await app.locator('.f-roster tbody tr').getByRole('button',{name:'Otwórz'}).click()
 await expect(app.getByRole('textbox',{name:'Notatka zespołu sprzedaży'})).toHaveValue('')
})

