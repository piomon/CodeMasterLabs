test('mobile full-page native modal traps focus, escapes and restores the trigger',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/demos/real-estate')
 const app=page.locator('main.forma-app')
 await app.getByRole('searchbox',{name:'Szukaj numeru mieszkania'}).fill('A-03')
 await expect(app.locator('.f-card h3')).toHaveText(['A-03'])
 const trigger=app.getByRole('button',{name:'Zobacz'})
 await trigger.click()
 const dialog=app.getByRole('dialog',{name:'Apartament A-03'})
 await expect(dialog).toBeVisible()
 await expect(dialog).toHaveJSProperty('open',true)
 await expect(dialog.getByRole('img',{name:/Poglądowy plan mieszkania A-03/})).toBeVisible()
 await page.keyboard.press('Shift+Tab')
 await expect(dialog.locator('select,button').last()).toBeFocused()
 await page.keyboard.press('Escape')
 await expect(dialog).toHaveCount(0)
 await expect(trigger).toBeFocused()
 await app.getByRole('button',{name:'Wybrane'}).click()
 await expect(app.getByRole('heading',{level:1,name:'Wybrane mieszkania'})).toBeVisible()
 await expect(app.getByRole('heading',{level:1})).toHaveCount(1)
})

