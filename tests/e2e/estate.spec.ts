test('PL residence filters lead to an actual detail and a local-only reservation persisted after reload and across locales',async({page})=>{
 await page.goto('/demos/real-estate')
 const app=page.locator('main.forma-app')
 await expect(app.getByRole('heading',{name:'Mieszkania z przestrzenią na więcej.'})).toBeVisible()
 await app.getByRole('searchbox',{name:'Szukaj numeru mieszkania'}).fill('A-03')
 await app.getByRole('combobox',{name:'Liczba pokoi'}).selectOption('2')
 await app.getByRole('combobox',{name:'Piętro'}).selectOption('1')
 await app.getByRole('combobox',{name:'Dostępność'}).selectOption('available')
 await expect(app.locator('.f-card')).toHaveCount(1)
 await expect(app.locator('.f-card h3')).toHaveText(['A-03'])
 await app.locator('.f-card').getByRole('button',{name:'Zobacz'}).click()
 const detail=app.getByRole('dialog',{name:'Apartament A-03'})
  await expect(detail.getByRole('img',{name:/Poglądowy plan mieszkania A-03: 2 pokoje/})).toBeVisible()
 await expect(detail).toContainText('CENA')
 await detail.getByRole('button',{name:'Zarezerwuj w demo'}).click()
 const confirmation=app.getByRole('dialog',{name:'Potwierdź rezerwację'})
 await expect(confirmation).toContainText('nie tworzy rzeczywistej rezerwacji')
 await confirmation.getByRole('button',{name:'Potwierdź w demo'}).click()
 await expect(app.locator('.f-empty')).toBeVisible()
 await app.getByRole('combobox',{name:'Dostępność'}).selectOption('reserved')
 await expect(app.locator('.f-card')).toHaveCount(1)
 await expect(app.locator('.f-card .f-status')).toHaveText(['Zarezerwowane'])
 await page.reload()
 await app.getByRole('searchbox',{name:'Szukaj numeru mieszkania'}).fill('A-03')
 await expect(app.locator('.f-card .f-status')).toHaveText(['Zarezerwowane'])
 await page.goto('/en/demos/real-estate')
 const english=page.locator('main.forma-app')
 await english.getByRole('searchbox',{name:'Search residence number'}).fill('A-03')
 await expect(english.locator('.f-card .f-status')).toHaveText(['Reserved'])
})

